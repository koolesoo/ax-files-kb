def make_body(topic_desc: str, expert_names: list[str]) -> str:
    parts = [
        f"Документ {topic_desc}.",
        random.choice(PARAGRAPHS),
        random.choice(PARAGRAPHS),
    ]
    if expert_names and random.random() > 0.35:
        name = random.choice(expert_names)
        parts.append(
            f"По вопросам применения практики рекомендуется обратиться к {name} — "
            f"консультации фиксируются в карточке эксперта."
        )
    parts.extend(random.sample(PARAGRAPHS, k=min(3, len(PARAGRAPHS))))
    return "\n\n".join(parts)


def make_title(i: int, topic: str, section: str, doc_type: str) -> str:
    """Уникальное название: базовый шаблон + опциональный суффикс или комбинация с темой."""
    base = TITLE_TEMPLATES[i % len(TITLE_TEMPLATES)]
    if random.random() < 0.35:
        # Вариант: тема встроена в узнаваемый формат
        patterns = [
            f"{topic.capitalize()} · {section.lower()}",
            f"Материал по теме «{topic}» · {section}",
            f"{base.split('·')[0].strip()} · {section.lower()}",
        ]
        base = random.choice(patterns)
    suffix = random.choice(TITLE_SUFFIXES)
    if suffix and suffix.strip() not in base:
        base = base + suffix
    return base


